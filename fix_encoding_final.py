#!/usr/bin/env python3
# -*- coding: utf-8 -*-

# 파일을 바이너리로 읽어서 직접 수정
with open('public/admin.html', 'rb') as f:
    content = f.read()

# 깨진 한글 텍스트를 올바른 한글로 교체
content = content.replace(
    b'<title>LRQA \xec\x9d\x98\xeb\xa1\x9c\xec\x9a\xb0 \xec\x8b\x9c\xec\x8a\xa4\xed\x85\x9c</title>',
    b'<title>LRQA \xea\xb4\x80\xeb\xa6\xac\xec\x9e\x90 \xec\x8b\x9c\xec\x8a\xa4\xed\x85\x9c</title>'
)

content = content.replace(
    b'<h2 style="text-align: center; margin-bottom: 30px;">LRQA \xec\x9d\x98\xeb\xa1\x9c\xec\x9a\xb0 \xeb\xa1\x9c\xea\xb7\xb8\xec\x9d\xb8</h2>',
    b'<h2 style="text-align: center; margin-bottom: 30px;">LRQA \xea\xb4\x80\xeb\xa6\xac\xec\x9e\x90 \xeb\xa1\x9c\xea\xb7\xb8\xec\x9d\xb8</h2>'
)

content = content.replace(
    b'<h1>LRQA \xec\x9d\x98\xeb\xa1\x9c\xec\x9a\xb0 \xec\x8b\x9c\xec\x8a\xa4\xed\x85\x9c</h1>',
    b'<h1>LRQA \xea\xb4\x80\xeb\xa6\xac\xec\x9e\x90 \xec\x8b\x9c\xec\x8a\xa4\xed\x85\x9c</h1>'
)

# 파일을 UTF-8로 저장
with open('public/admin.html', 'wb') as f:
    f.write(content)

print("바이너리 레벨에서 인코딩 문제 수정 완료")
