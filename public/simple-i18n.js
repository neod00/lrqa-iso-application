// 언어 변경 함수
function switchLanguage(lang) {
    currentLanguage = lang;
    localStorage.setItem('language', lang);
    updatePageLanguage();
}

// 번역 함수
function t(key) {
    return translations[currentLanguage]?.[key] || translations['ko']?.[key] || key;
}

// 페이지 언어 업데이트
        function updatePageLanguage() {
            const elements = document.querySelectorAll('[data-i18n]');
            elements.forEach(element => {
                const key = element.getAttribute('data-i18n');
                const translation = t(key);

                if (element.tagName === 'INPUT' && element.type === 'text') {
                    element.placeholder = translation;
                } else if (element.tagName === 'TEXTAREA') {
                    element.placeholder = translation;
                } else {
                    // HTML 내용이 포함된 경우 innerHTML 사용
                    if (translation.includes('<a ') || translation.includes('</a>')) {
                        element.innerHTML = translation;
                    } else {
                        element.textContent = translation;
                    }
                }
            });
            
            // Handle placeholder translations
            const placeholderElements = document.querySelectorAll('[data-i18n-placeholder]');
            placeholderElements.forEach(element => {
                const key = element.getAttribute('data-i18n-placeholder');
                const translation = t(key);
                element.placeholder = translation;
            });

            // Handle value translations
            const valueElements = document.querySelectorAll('[data-i18n-value]');
            valueElements.forEach(element => {
                const key = element.getAttribute('data-i18n-value');
                const translation = t(key);
                element.value = translation;
            });
            
            // Handle innerHTML translations for complex content
            const innerHTMLElements = document.querySelectorAll('[data-i18n-html]');
            innerHTMLElements.forEach(element => {
                const key = element.getAttribute('data-i18n-html');
                const translation = t(key);
                element.innerHTML = translation;
            });
        }

